import java.io.*;
import java.net.*;
import java.nio.charset.StandardCharsets;
import java.nio.file.*;
import java.util.*;

/** Test-only transport with synthetic certificate. Never packaged in the JP agent. */
public class CertificateBridgeWindowsTest {
    static final String COMPANY="synthetic-company", JOB="synthetic-job";
    static String thumbprint;
    static Path folder;
    static int packages, finishes;
    static boolean unavailable;
    static final byte[] CONTENT="JPGED SYNTHETIC WINDOWS SIGNATURE".getBytes(StandardCharsets.UTF_8);
    public static void main(String[] args) throws Exception {
        if(!System.getProperty("os.name").startsWith("Windows"))throw new AssertionError("Windows required");
        folder=Paths.get(args[0]);thumbprint=args[1];
        Path bindings=Paths.get(System.getenv("LOCALAPPDATA"),"JPBiometria","certificados");Files.createDirectories(bindings);
        Files.write(bindings.resolve(COMPANY+".json"),"{\"fingerprint\":\"fixture\",\"thumbprint\":\"fixture\"}".getBytes(StandardCharsets.UTF_8));
        URL.setURLStreamHandlerFactory(protocol->protocol.equals("https")?new URLStreamHandler(){protected URLConnection openConnection(URL url){return new FixtureConnection(url);}}:null);
        Map<String,Object> request=new LinkedHashMap<>();request.put("token",String.join("",Collections.nCopies(120,"a")));request.put("empresaId",COMPANY);request.put("jobId",JOB);
        unavailable=true;
        try{CertificateBridge.execute("sign",request);throw new AssertionError("API failure accepted");}
        catch(BioFailure e){if(!"CERT_TEST_UNAVAILABLE".equals(e.code))throw new AssertionError("Failure did not preserve server diagnostic: "+e.code);}
        if(finishes!=0)throw new AssertionError("Signing completed during API failure");
        unavailable=false;
        Map<String,Object> answer=CertificateBridge.execute("sign",request);
        if(!Boolean.TRUE.equals(answer.get("completed"))||!(answer.get("item") instanceof Map)||packages!=2||finishes!=1)throw new AssertionError("Nested certificate response failed");
        if(!Files.isRegularFile(folder.resolve("signed.der")))throw new AssertionError("No CMS generated by Windows");
        // Flat biometric request grammar and duplicate/depth protections remain intact.
        for(String value:Arrays.asList("{\"template\":{}}","{\"template\":[]}")){
            try{Json.object(value);throw new AssertionError("Nested browser request accepted");}catch(IllegalArgumentException expected){}
        }
        for(String value:Arrays.asList("{\"x\":{\"a\":1,\"a\":2}}","{\"x\":[1,]}","{\"x\":01}","{\"x\":[]} trailing")){
            try{Json.responseObject(value);throw new AssertionError("Invalid API response accepted");}catch(IllegalArgumentException expected){}
        }
        System.out.println("Certificate bridge: nested API -> production Windows signer -> nested confirmation; retry passed without reader calls.");
    }
    static class FixtureConnection extends HttpURLConnection {
        final ByteArrayOutputStream posted=new ByteArrayOutputStream();
        FixtureConnection(URL url){super(url);if(!url.getHost().equals("g4pdu3t1va.execute-api.sa-east-1.amazonaws.com"))throw new AssertionError("Unexpected API host");}
        public void connect(){} public void disconnect(){} public boolean usingProxy(){return false;}
        public OutputStream getOutputStream(){return posted;}
        public int getResponseCode(){if(getRequestMethod().equals("GET"))packages++;return unavailable?503:200;}
        public InputStream getErrorStream(){return new ByteArrayInputStream("{\"ok\":false,\"code\":\"CERT_TEST_UNAVAILABLE\",\"error\":\"Synthetic unavailable\"}".getBytes(StandardCharsets.UTF_8));}
        public InputStream getInputStream() throws IOException {
            if(!url.getPath().equals("/api/jpged/assinaturas/"+JOB))throw new AssertionError("Unexpected API route");
            String response;
            if(getRequestMethod().equals("GET")){
                response="{\"ok\":true,\"package\":{\"jobId\":\""+JOB+"\",\"empresaId\":\""+COMPANY+"\",\"thumbprint\":\""+thumbprint+"\",\"certificateFingerprint\":\"fixture\",\"contentBase64\":\""+Base64.getEncoder().encodeToString(CONTENT)+"\"}}";
            }else if(getRequestMethod().equals("POST")){
                finishes++;
                Map<String,Object> body=Json.object(new String(posted.toByteArray(),StandardCharsets.UTF_8));
                Files.write(folder.resolve("signed.der"),Base64.getDecoder().decode((String)body.get("cms")));
                response="{\"ok\":true,\"completed\":true,\"item\":{\"status\":\"assinada\",\"itens\":[{\"quantidade\":1.5}],\"certificacao\":{\"status\":\"certificado\"}}}";
            }else throw new AssertionError("Unexpected method");
            return new ByteArrayInputStream(response.getBytes(StandardCharsets.UTF_8));
        }
    }
}
